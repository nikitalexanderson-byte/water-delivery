CREATE TABLE accounts (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email text NOT NULL UNIQUE CHECK(email=lower(email)),
 name text NOT NULL, password_hash text NOT NULL,
 role text NOT NULL CHECK(role IN ('operator','dispatcher','driver','manager'))
);
CREATE TABLE sessions (
 digest text PRIMARY KEY, account_id int NOT NULL REFERENCES accounts, expires_at timestamptz NOT NULL
);
CREATE TABLE vehicles (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL,
 capacity_kg int NOT NULL CHECK(capacity_kg>0), extra_kg int NOT NULL DEFAULT 0 CHECK(extra_kg>=0 AND extra_kg<=capacity_kg),
 length_mm int NOT NULL, body_height_mm int NOT NULL, platform_mm int, total_height_mm int CHECK(total_height_mm>0)
);
CREATE TABLE shifts (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 driver_id int NOT NULL REFERENCES accounts, vehicle_id int NOT NULL REFERENCES vehicles,
 date date NOT NULL, start_min int NOT NULL, end_min int NOT NULL, has_loader boolean NOT NULL DEFAULT false,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','confirmed','active','closed')),
 CHECK(start_min>=0 AND start_min<end_min AND end_min<1440), UNIQUE(driver_id,date), UNIQUE(vehicle_id,date)
);
CREATE TABLE customers (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, phone text NOT NULL, address text NOT NULL
);
CREATE TABLE trips (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,shift_id int NOT NULL REFERENCES shifts,
 number int NOT NULL CHECK(number>0), status text NOT NULL DEFAULT 'planned' CHECK(status IN ('planned','active','returned')),
 actual_start int, actual_return int, UNIQUE(shift_id,number),
 CHECK(actual_return IS NULL OR actual_return>=actual_start)
);
CREATE UNIQUE INDEX one_active_trip ON trips(shift_id) WHERE status='active';
CREATE TABLE orders (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id int NOT NULL REFERENCES customers,
 name text NOT NULL, phone text NOT NULL, address text NOT NULL, address_verified boolean NOT NULL DEFAULT false,
 date date NOT NULL,window_start int NOT NULL,window_end int NOT NULL,
 water int NOT NULL CHECK(water BETWEEN 1 AND 10000),new_shells int NOT NULL CHECK(new_shells BETWEEN 0 AND water),
 water_price int NOT NULL CHECK(water_price>=0),shell_price int NOT NULL CHECK(shell_price>=0),
 total bigint GENERATED ALWAYS AS (water::bigint*water_price+new_shells::bigint*shell_price) STORED,
 category text NOT NULL CHECK(category IN ('retail','wholesale')),
 payment_method text NOT NULL CHECK(payment_method IN ('cash','bank')),company text NOT NULL DEFAULT '',
 floor int NOT NULL DEFAULT 1,lift boolean NOT NULL DEFAULT true,checkpoint boolean NOT NULL DEFAULT false,
 height_limit_mm int CHECK(height_limit_mm>0),note text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','assigned','delivered','cancelled')),
 version int NOT NULL DEFAULT 1, reason text, trip_id int REFERENCES trips, position int, eta int,
 paid boolean NOT NULL DEFAULT false, CHECK(payment_method <> 'bank' OR length(trim(company))>0),
 CHECK(window_start>=0 AND window_start<window_end AND window_end<1440),
 CHECK((status IN ('assigned','delivered'))=(trip_id IS NOT NULL))
);
CREATE INDEX orders_day ON orders(date,status);
CREATE TABLE rates (
 category text NOT NULL, has_loader boolean NOT NULL, per_stop int NOT NULL CHECK(per_stop>=0),
 per_bottle int NOT NULL CHECK(per_bottle>=0), PRIMARY KEY(category,has_loader)
);
