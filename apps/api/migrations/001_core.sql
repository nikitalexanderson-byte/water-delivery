CREATE TABLE inventory (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, trip_id int NOT NULL REFERENCES trips,
 order_id int UNIQUE REFERENCES orders, kind text NOT NULL CHECK(kind IN ('load','delivery')),
 full_delta int NOT NULL, empty_delta int NOT NULL CHECK(empty_delta>=0), sold_shells int NOT NULL DEFAULT 0,
 CHECK((kind='load' AND order_id IS NULL AND full_delta>0) OR (kind='delivery' AND order_id IS NOT NULL AND full_delta<0))
);
CREATE UNIQUE INDEX one_load ON inventory(trip_id) WHERE kind='load';
CREATE TABLE receipts (
 order_id int PRIMARY KEY REFERENCES orders, amount bigint NOT NULL CHECK(amount>=0),
 method text NOT NULL CHECK(method IN ('cash','bank')), confirmed boolean NOT NULL,
 earnings int NOT NULL, per_stop int NOT NULL, per_bottle int NOT NULL
);
CREATE TABLE settlements (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shift_id int UNIQUE NOT NULL REFERENCES shifts,
 expected jsonb NOT NULL, actual jsonb NOT NULL, difference jsonb NOT NULL, matched boolean NOT NULL,
 delivered_water int NOT NULL,delivered_stops int NOT NULL, sold_shells int NOT NULL, earnings bigint NOT NULL,
 unpaid bigint NOT NULL,loader_minutes int NOT NULL, reviewed boolean NOT NULL DEFAULT false, reviewed_by int REFERENCES accounts,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor int REFERENCES accounts,
 event text NOT NULL, entity_id int, details jsonb NOT NULL DEFAULT '{}',created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE requests (
 actor int REFERENCES accounts, key text NOT NULL, signature text NOT NULL,result jsonb NOT NULL, PRIMARY KEY(actor,key)
);
