CREATE TABLE invitations (
  digest text PRIMARY KEY,
  team_id integer NOT NULL REFERENCES teams,
  role text NOT NULL CHECK (role IN ('operator','dispatcher','driver')),
  created_by integer NOT NULL REFERENCES accounts,
  expires_at timestamptz NOT NULL,
  used_by integer UNIQUE REFERENCES accounts,
  used_at timestamptz
);
CREATE INDEX invitations_expires ON invitations (expires_at);
