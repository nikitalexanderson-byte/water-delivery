CREATE TABLE team_bases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id integer NOT NULL REFERENCES teams,
  address text NOT NULL CHECK (length(trim(address)) BETWEEN 1 AND 300),
  lat double precision CHECK (lat BETWEEN -90 AND 90),
  lon double precision CHECK (lon BETWEEN -180 AND 180),
  CHECK ((lat IS NULL)=(lon IS NULL)),
  UNIQUE (team_id,id)
);

ALTER TABLE teams ADD COLUMN active_base_id integer;
ALTER TABLE teams ADD FOREIGN KEY (id,active_base_id) REFERENCES team_bases(team_id,id);
INSERT INTO team_bases (team_id,address,lat,lon)
  SELECT id,COALESCE(NULLIF(trim(base_address),''),'Производственная база'),base_lat,base_lon
  FROM teams WHERE trim(base_address)<>'' OR base_lat IS NOT NULL;
UPDATE teams t SET active_base_id=b.id FROM team_bases b WHERE t.id=b.team_id;

